import sys
import pandas as pd
from typing import Dict, List

from helm.benchmark.presentation.taxonomy_info import TaxonomyInfo
from helm.benchmark.scenarios.scenario import (
    Input,
    Scenario,
    Instance,
    TEST_SPLIT,
    CORRECT_TAG,
    Reference,
    Output,
    ScenarioMetadata,
)
from helm.common.general import check_file_exists


class Pp26AdolescentPrivacyScenario(Scenario):
    """
    This dataset features synthetic, PHI-free clinical scenarios generated by an LLM and
    reviewed by clinicians. The scenario evaluates the ability of an LLM to determine whether
    patient privacy rights and parental notification requirements apply to adolescent patients
    under HIPAA and state-specific privacy laws.
    """

    name = "pp26_adolescent_privacy"
    description = (
        "AdolescentPrivacy is a benchmark of synthetic clinical scenarios that tests whether a model "
        "can determine when HIPAA and state privacy laws permit adolescent patients to access, "
        "control, and restrict disclosure of their health information, including when parental "
        "notification and consent are required or prohibited."
    )
    tags = ["knowledge", "reasoning", "biomedical"]

    POSSIBLE_ANSWER_CHOICES: List[str] = ["A", "B"]

    def __init__(self, data_path: str):
        super().__init__()
        self.data_path = data_path

    def create_benchmark(self, excel_path) -> Dict[str, str]:
        data = {}
        # Read the "Test cases" sheet from the Excel file
        df = pd.read_excel(excel_path, sheet_name="Test cases")
        
        for _, row in df.iterrows():
            question = row["question"]
            note = row["note"]
            answer = row["provided_label"]
            prompt = (
                "For a paediatric progress note that will be released to a parent through the portal, "
                "determine whether the note contains the patient's own information in a named confidential category that should be withheld.\n\n"
                "Confidential categories: sexual and reproductive health; substance use; mental health; family safety.\n"
                "Rules: Routine screening or guidance with no concerning finding is not withheld. Information about other people is not the patient's own.\n\n"
                f"{question}\n\n"
                f"Clinical Note:\n{note}\n\n"
                "Answer:\n"
                "A: The note contains withholdable information in that category.\n"
                "B: The note does not contain withholdable information in that category.\n\n"
                "Respond with only A or B and no additional explanation."
            )
            # Store all other fields as metadata
            meta_data = {
                k: str(v) if pd.notna(v) else ""
                for k, v in row.items()
                if k not in ["question", "note", "provided_label"]
            }
            data[prompt] = (answer, meta_data)
                
        return data

    def get_instances(self, output_path: str) -> List[Instance]:
        check_file_exists(
            self.data_path, msg=f"[Pp26AdolescentPrivacyScenario] Required data file not found: '{self.data_path}'"
        )
        instances: List[Instance] = []
        benchmark_data = self.create_benchmark(self.data_path)

        for prompt, (answer, meta_data) in benchmark_data.items():
            assert answer in Pp26AdolescentPrivacyScenario.POSSIBLE_ANSWER_CHOICES
            references: List[Reference] = [
                Reference(Output(text=pred_answer), tags=[CORRECT_TAG] if pred_answer == answer else [])
                for pred_answer in Pp26AdolescentPrivacyScenario.POSSIBLE_ANSWER_CHOICES
            ]
            instances.append(
                Instance(
                    input=Input(text=prompt),
                    references=references,
                    split=TEST_SPLIT,
                    extra_data=meta_data,
                )
            )

        return instances

    def get_metadata(self):
        return ScenarioMetadata(
            name="pp26_adolescent_privacy",
            display_name="AdolescentPrivacy",
            description=(
                "Predict whether HIPAA and state privacy laws permit or restrict disclosure of "
                "adolescent patient health information to parents or guardians."
            ),
            taxonomy=TaxonomyInfo(
                task="Classification",
                what="Classify whether parental access to adolescent patient information is permitted under privacy laws",
                when="Any",
                who="Clinician, Parent, Guardian, Adolescent Patient, Caregiver",
                language="English",
            ),
            main_metric="exact_match",
            main_split="test",
        )

import pandas as pd
from typing import Dict, List, cast

from helm.benchmark.presentation.taxonomy_info import TaxonomyInfo
from helm.benchmark.scenarios.scenario import (
    Input,
    Scenario,
    Instance,
    TEST_SPLIT,
    CORRECT_TAG,
    Reference,
    Output,
    ScenarioMetadata,
)
from helm.common.general import check_file_exists


class PP26ProxyLeakScenario(Scenario):
    """
    This dataset features synthetic, PHI-free clinical scenarios generated by an LLM and
    reviewed by clinicians. The scenario evaluates the ability of an LLM to determine whether
    proxy access to patient portals creates privacy risks through message leakage.
    """

    name = "pp26_proxy_leak"
    description = (
        "ProxyLeak is a benchmark of synthetic clinical scenarios that tests whether a model "
        "can identify privacy risks when proxy account holders access patient portal messages, "
        "including risks of unintended disclosure of sensitive health information."
    )
    tags = ["knowledge", "reasoning", "biomedical"]

    POSSIBLE_ANSWER_CHOICES: List[str] = ["A", "B"]

    def __init__(self, data_path: str):
        super().__init__()
        self.data_path = data_path

    def create_benchmark(self, excel_path) -> Dict[str, tuple[str, Dict[str, str]]]:
        data = {}
        # Read the "Test cases" sheet from the Excel file
        df = pd.read_excel(excel_path, sheet_name="Test cases")

        for _, row in df.iterrows():
            question = row["question"]
            message = row["message"]
            answer = cast(str, row["provided_label"]).strip().upper()
            prompt = (
                "For a clinician's portal message to an adolescent, determine whether a parent with proxy access who reads it "
                "would learn something about the patient's own sexual health, substance use, mental health, reproductive health, "
                "or family safety that the patient may keep confidential.\n\n"
                f"{question}\n\n"
                f"Portal Message:\n{message}\n\n"
                "Answer:\n"
                "A: Yes, a parent with proxy access would learn confidential information.\n"
                "B: No, no confidential information would be disclosed to a parent with proxy access.\n\n"
                "Respond with only A or B and no additional explanation."
            )
            # Store all other fields as metadata
            meta_data = {
                k: str(v) if pd.notna(v) else ""
                for k, v in row.items()
                if k not in ["question", "message", "provided_label"]
            }
            data[prompt] = (answer, meta_data)

        return data

    def get_instances(self, output_path: str) -> List[Instance]:
        check_file_exists(
            self.data_path, msg=f"[PP26ProxyLeakScenario] Required data file not found: '{self.data_path}'"
        )
        instances: List[Instance] = []
        benchmark_data = self.create_benchmark(self.data_path)

        for prompt, (answer, meta_data) in benchmark_data.items():
            assert answer in PP26ProxyLeakScenario.POSSIBLE_ANSWER_CHOICES
            references: List[Reference] = [
                Reference(Output(text=pred_answer), tags=[CORRECT_TAG] if pred_answer == answer else [])
                for pred_answer in PP26ProxyLeakScenario.POSSIBLE_ANSWER_CHOICES
            ]
            instances.append(
                Instance(
                    input=Input(text=prompt),
                    references=references,
                    split=TEST_SPLIT,
                    extra_data=meta_data,
                )
            )

        return instances

    def get_metadata(self):
        return ScenarioMetadata(
            name="pp26_proxy_leak",
            display_name="ProxyLeak",
            description=(
                "Predict whether proxy access to patient portal messages creates privacy risks "
                "through unintended disclosure of sensitive health information."
            ),
            taxonomy=TaxonomyInfo(
                task="Classification",
                what="Classify whether proxy access to portal messages poses privacy risks",
                when="Any",
                who="Clinician, Patient, Proxy Account Holder, Parent, Guardian",
                language="English",
            ),
            main_metric="exact_match",
            main_split="test",
        )

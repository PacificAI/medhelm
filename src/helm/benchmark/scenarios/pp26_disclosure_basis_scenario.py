import pandas as pd
from typing import Dict, List

from helm.benchmark.presentation.taxonomy_info import TaxonomyInfo
from helm.benchmark.scenarios.scenario import (
    Input,
    Scenario,
    Instance,
    TEST_SPLIT,
    CORRECT_TAG,
    Reference,
    Output,
    ScenarioMetadata,
)
from helm.common.general import check_file_exists


class Pp26DisclosureBasisScenario(Scenario):
    """
    This dataset features synthetic, PHI-free clinical scenarios generated by an LLM and
    reviewed by clinicians. The scenario evaluates the ability of an LLM to determine the
    legal basis for disclosure of patient health information under HIPAA and other regulations.
    """

    name = "pp26_disclosure_basis"
    description = (
        "DisclosureBasis is a benchmark of synthetic clinical scenarios that tests whether a model "
        "can determine the legal basis and regulatory authority that permits the disclosure of "
        "patient health information, including HIPAA, 42 CFR Part 2, and state privacy laws."
    )
    tags = ["knowledge", "reasoning", "biomedical"]

    POSSIBLE_ANSWER_CHOICES: List[str] = ["A", "B", "C"]

    def __init__(self, data_path: str):
        super().__init__()
        self.data_path = data_path

    def create_benchmark(self, excel_path) -> Dict[str, tuple[str, Dict[str, str]]]:
        data = {}
        # Read the "Test cases" sheet from the Excel file
        df = pd.read_excel(excel_path, sheet_name="Test cases")

        for _, row in df.iterrows():
            question = row["question"]
            scenario = row["scenario"]
            answer = row["provided_label"]
            prompt = (
                "Determine whether a disclosure of health information is permitted, not permitted, or undecidable.\n\n"
                "Legal rules: HIPAA (45 CFR Parts 160 and 164), 42 CFR Part 2 for substance-use treatment records, and state law where applicable.\n\n"
                f"{question}\n\n"
                f"Scenario:\n{scenario}\n\n"
                "Answer:\n"
                "A: Permitted or access must be granted on these facts.\n"
                "B: Not permitted or access may be denied.\n"
                "C: The answer turns on a fact the scenario does not state.\n\n"
                "Respond with only A, B, or C and no additional explanation."
            )
            # Store all other fields as metadata
            meta_data = {
                k: str(v) if pd.notna(v) else ""
                for k, v in row.items()
                if k not in ["question", "scenario", "provided_label"]
            }
            data[prompt] = (answer, meta_data)

        return data

    def get_instances(self, output_path: str) -> List[Instance]:
        check_file_exists(
            self.data_path, msg=f"[Pp26DisclosureBasisScenario] Required data file not found: '{self.data_path}'"
        )
        instances: List[Instance] = []
        benchmark_data = self.create_benchmark(self.data_path)

        for prompt, (answer, meta_data) in benchmark_data.items():
            assert answer in Pp26DisclosureBasisScenario.POSSIBLE_ANSWER_CHOICES
            references: List[Reference] = [
                Reference(Output(text=pred_answer), tags=[CORRECT_TAG] if pred_answer == answer else [])
                for pred_answer in Pp26DisclosureBasisScenario.POSSIBLE_ANSWER_CHOICES
            ]
            instances.append(
                Instance(
                    input=Input(text=prompt),
                    references=references,
                    split=TEST_SPLIT,
                    extra_data=meta_data,
                )
            )

        return instances

    def get_metadata(self):
        return ScenarioMetadata(
            name="pp26_disclosure_basis",
            display_name="DisclosureBasis",
            description=(
                "Predict whether patient health information disclosure is permitted under the "
                "applicable legal basis (HIPAA, 42 CFR Part 2, state privacy laws, etc.)."
            ),
            taxonomy=TaxonomyInfo(
                task="Classification",
                what="Classify whether disclosure of patient health information is permitted under applicable regulations",
                when="Any",
                who="Clinician, Healthcare Administrator, Compliance Officer, Covered Entity",
                language="English",
            ),
            main_metric="exact_match",
            main_split="test",
        )

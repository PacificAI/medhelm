import sys
import pandas as pd
from typing import Dict, List

from helm.benchmark.presentation.taxonomy_info import TaxonomyInfo
from helm.benchmark.scenarios.scenario import (
    Input,
    Scenario,
    Instance,
    TEST_SPLIT,
    CORRECT_TAG,
    Reference,
    Output,
    ScenarioMetadata,
)
from helm.common.general import check_file_exists


class PP26ProxyAccessScenario(Scenario):
    """
    This dataset features synthetic, PHI-free clinical scenarios generated by an LLM and
    reviewed by clinicians. The scenario evaluates the ability of an LLM to determine whether
    proxy account holders should have access to patient health information in portal messages.
    """

    name = "pp26_proxy_access"
    description = (
        "ProxyAccess is a benchmark of synthetic clinical scenarios that tests whether a model "
        "can determine appropriate proxy access permissions to patient health information in portals, "
        "considering HIPAA regulations, state privacy laws, and clinical context."
    )
    tags = ["knowledge", "reasoning", "biomedical"]

    POSSIBLE_ANSWER_CHOICES: List[str] = ["A", "B", "C", "D"]

    def __init__(self, data_path: str):
        super().__init__()
        self.data_path = data_path

    def create_benchmark(self, excel_path) -> Dict[str, str]:
        data = {}
        # Read the "Test cases" sheet from the Excel file
        df = pd.read_excel(excel_path, sheet_name="Test cases")
        
        for _, row in df.iterrows():
            question = row["question"]
            message = row["message"]
            answer = row["provided_label"]
            prompt = (
                f"{question}\n\n"
                f"Account and message details:\n{message}\n\n"
                "Answer based on the clinic's proxy-access policy following 45 CFR 164.502(g), 164.522, and state minor-consent law:\n"
                "A: Send the requested information to this sender.\n"
                "B: Do not send it to this sender; provide it to the patient directly or decline.\n"
                "C: Verify the sender's identity or authority before replying.\n"
                "D: Cannot determine, because a fact the policy turns on is not recorded.\n\n"
                "Respond with only A, B, C, or D and no additional explanation."
            )
            # Store all other fields as metadata
            meta_data = {
                k: str(v) if pd.notna(v) else ""
                for k, v in row.items()
                if k not in ["question", "message", "provided_label"]
            }
            data[prompt] = (answer, meta_data)
                
        return data

    def get_instances(self, output_path: str) -> List[Instance]:
        check_file_exists(
            self.data_path, msg=f"[PP26ProxyAccessScenario] Required data file not found: '{self.data_path}'"
        )
        instances: List[Instance] = []
        benchmark_data = self.create_benchmark(self.data_path)

        for prompt, (answer, meta_data) in benchmark_data.items():
            assert answer in PP26ProxyAccessScenario.POSSIBLE_ANSWER_CHOICES
            references: List[Reference] = [
                Reference(Output(text=pred_answer), tags=[CORRECT_TAG] if pred_answer == answer else [])
                for pred_answer in PP26ProxyAccessScenario.POSSIBLE_ANSWER_CHOICES
            ]
            instances.append(
                Instance(
                    input=Input(text=prompt),
                    references=references,
                    split=TEST_SPLIT,
                    extra_data=meta_data,
                )
            )

        return instances

    def get_metadata(self):
        return ScenarioMetadata(
            name="pp26_proxy_access",
            display_name="ProxyAccess",
            description=(
                "Predict whether proxy account holders should have access to patient health information "
                "in portal messages under applicable regulations."
            ),
            taxonomy=TaxonomyInfo(
                task="Classification",
                what="Classify appropriate proxy access permissions to patient portal messages",
                when="Any",
                who="Clinician, Patient, Proxy Account Holder, Parent, Guardian",
                language="English",
            ),
            main_metric="exact_match",
            main_split="test",
        )
